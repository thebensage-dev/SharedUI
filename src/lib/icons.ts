export type IconName = keyof typeof ICONS;

/** Every icon name, in order (for the CMS's picker). */
export const ICON_NAMES = Object.keys(ICONS) as IconName[];

/** The icon with that name; a dot when the name is unknown, nothing when it's empty. */
export function iconByName(name: string | null | undefined): LucideIcon | undefined {
  if (!name) return undefined;
  return (ICONS as Record<string, LucideIcon>)[name] ?? Circle;
}

/** Like `iconByName`, for places that always need an icon. */
export const iconOrDot = (name: string | null | undefined): LucideIcon =>
  iconByName(name) ?? Circle;
